#!/usr/bin/env python3
"""Make the example photo shown on the paper before visitors pick their own.

Crops the photo to the shape of the paper (keeping the given point in the middle) and
writes it as a data URI into docs/assets/default-image.js, so the page also works when
opened straight from disk. Re-encoding also drops any metadata (location, camera...).

Usage: python3 tools/make_default_image.py [photo] [--center X Y]
  photo     default: tools/default-photo.jpeg
  --center  point to keep in the middle of the crop, as fractions of width and height
            (default 0.5 0.5 = the middle of the photo)
Requirements: pillow
"""
import argparse
import base64
import io
import json
import re
from pathlib import Path

from PIL import Image, ImageOps

TOOLS = Path(__file__).resolve().parent
ASSETS = TOOLS.parent / "docs" / "assets"
MAX_SIDE = 1400   # the paper is about 750x1070 px in the template; a little extra keeps zoom sharp


def paper_aspect():
    """Width / height of the paper's photo area, from the generated template."""
    return float(re.search(r'"aspect":([0-9.]+)', (ASSETS / "template-data.js").read_text()).group(1))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("photo", nargs="?", default=str(TOOLS / "default-photo.jpeg"))
    ap.add_argument("--center", nargs=2, type=float, default=(0.5, 0.5), metavar=("X", "Y"))
    args = ap.parse_args()

    im = ImageOps.exif_transpose(Image.open(args.photo)).convert("RGB")   # apply phone rotation
    w, h = im.size
    aspect = paper_aspect()
    cw, ch = (w, w / aspect) if w / h < aspect else (h * aspect, h)
    x0 = min(max(args.center[0] * w - cw / 2, 0), w - cw)
    y0 = min(max(args.center[1] * h - ch / 2, 0), h - ch)
    im = im.crop((round(x0), round(y0), round(x0 + cw), round(y0 + ch)))
    if max(im.size) > MAX_SIDE:
        im.thumbnail((MAX_SIDE, MAX_SIDE), Image.LANCZOS)

    buf = io.BytesIO()
    im.save(buf, "WEBP", quality=85, method=6)
    uri = "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()
    (ASSETS / "default-image.js").write_text(
        "/* Generated by tools/make_default_image.py - do not edit by hand. */\n"
        "window.MEME_DEFAULT_IMAGE = " + json.dumps(uri) + ";\n")
    print(f"crop {im.size}, {len(buf.getvalue()) // 1024} KB -> docs/assets/default-image.js")


if __name__ == "__main__":
    main()
